#!/usr/bin/env node
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const COHORTS_DIR = join(REPO_ROOT, 'var/cohorts');
const OUT_FILE = join(
  REPO_ROOT,
  'packages/fpl-client/src/score-distributions/distributions.generated.ts'
);

function log(msg) {
  process.stdout.write(`[${new Date().toISOString()}] ${msg}\n`);
}

async function listGameweeks() {
  const entries = await readdir(COHORTS_DIR, { withFileTypes: true });
  const gws = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const match = entry.name.match(/^gw(\d+)$/);
    if (!match) continue;
    gws.push(Number(match[1]));
  }
  return gws.sort((a, b) => a - b);
}

async function readDistribution(gw) {
  const path = join(COHORTS_DIR, `gw${gw}`, 'score-distribution.json');
  const raw = await readFile(path, 'utf8');
  return JSON.parse(raw);
}

async function main() {
  const gws = await listGameweeks();
  log(`found ${gws.length} gameweeks under ${relative(REPO_ROOT, COHORTS_DIR)}`);
  const payload = {};
  for (const gw of gws) {
    payload[gw] = await readDistribution(gw);
  }

  const body = `// AUTO-GENERATED by scripts/build-distributions-index.mjs — do not edit by hand.
// Source: var/cohorts/gw{N}/score-distribution.json
import type { ScoreDistributionFile } from '@simplyfpl/types';

export const DISTRIBUTIONS: Readonly<Record<number, ScoreDistributionFile>> = ${JSON.stringify(
    payload,
    null,
    2
  )};

export const DISTRIBUTION_GAMEWEEKS: readonly number[] = ${JSON.stringify(gws)};
`;
  await writeFile(OUT_FILE, body);
  log(`wrote ${relative(REPO_ROOT, OUT_FILE)} (${gws.length} GWs)`);
}

main().catch((err) => {
  log(`fatal: ${err.stack ?? err.message}`);
  process.exit(1);
});
